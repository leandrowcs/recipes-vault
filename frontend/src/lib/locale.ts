export function translate(locale: Locale, key: string): string {
  return messages[locale][key] ?? messages['en-US'][key] ?? key
}

export function translateError(locale: Locale, message: string): string {
  const exact: Record<string, string> = {
    'Firebase is not configured. Complete the setup before loading recipes.': 'storageNotConfigured',
    'Firebase is not configured.': 'firebaseNotConfigured',
    'The requested changes contain invalid recipe or pantry data.': 'invalidChanges',
    'The backup contains invalid recipe data.': 'invalidBackupData',
    'The backup is too large to restore. Choose a file smaller than 5 MB.': 'backupTooLargeError',
    'This file is not valid JSON. Your saved recipes were not changed.': 'invalidJson',
    'This backup has an unsupported format or invalid recipe data. Your saved recipes were not changed.': 'invalidBackupFormat',
    'This backup contains duplicate recipes. Your saved recipes were not changed.': 'duplicateBackupRecipes',
    'Saved recipe data could not be read. No data was changed.': 'legacyParseError',
    'Saved recipe data has an unsupported format. No data was changed.': 'legacyFormatError',
    'Saved recipe data is invalid or from an unsupported version. No data was changed.': 'legacyVersionError',
    'Saved recipe data contains duplicate IDs. No data was changed.': 'legacyDuplicateError',
    'Cannot save invalid recipe data.': 'invalidSaveData',
    'Cannot save recipes with duplicate IDs.': 'duplicateSaveData',
    'No supported recipe metadata was found on this page. Add the recipe manually.': 'noRecipeMetadata',
    'Use GET to search the recipe catalog.': 'apiUseGetMeals',
    'Enter a valid recipe ID.': 'invalidRecipeId',
    'Recipe discovery requires a production TheMealDB API key. See the deployment setup guide.': 'productionMealDbKey',
    'That recipe is not available in the catalog.': 'missingMeal',
    'The recipe catalog is temporarily unavailable. Try again later.': 'mealDbUnavailable',
    'Enter one ingredient using 2–60 letters.': 'invalidIngredientQuery',
    'Use GET to look up a product.': 'apiUseGetProduct',
    'Enter an 8, 12, 13, or 14 digit barcode.': 'invalidBarcodeApi',
    'Open Food Facts is rate-limiting requests. Try again in a minute.': 'offRateLimited',
    'Open Food Facts is temporarily unavailable. Try again later.': 'offUnavailable',
    'Use POST to import a recipe URL.': 'apiUsePostImport',
    'Send the recipe URL as JSON.': 'importUrlJson',
    'The recipe could not be imported. Add it manually or try again later.': 'importerFailed',
    'Login cancelled. Try again when you are ready.': 'signInCancelled',
    'Allow pop-ups for this site, then try again.': 'allowPopups',
    'Add this site domain under Firebase Authentication → Settings → Authorized domains.': 'authorizeDomain',
    'Enable Google under Firebase Authentication → Sign-in method.': 'enableGoogle',
    'Connect to the internet to sign in.': 'authNetwork',
    'Cloud access denied. Verify the owner UID in Firestore Rules.': 'cloudDenied',
    'Firebase is temporarily unavailable. Check your connection and retry.': 'firebaseUnavailable',
    'Unable to connect to your account. Check Firebase setup and try again.': 'authConnectionError',
  }
  const key = exact[message]
  if (key) return translate(locale, key)
  const invalidId = message.match(/^The (recipe|pantry) collection contains an invalid document ID\.$/)
  if (invalidId) return translate(locale, 'invalidDocumentId').replace('{kind}', locale === 'pt-BR' ? (invalidId[1] === 'recipe' ? 'receitas' : 'despensa') : invalidId[1])
  const duplicateIds = message.match(/^The (recipe|pantry) collection contains duplicate document IDs\.$/)
  if (duplicateIds) return translate(locale, 'duplicateDocumentIds').replace('{kind}', locale === 'pt-BR' ? (duplicateIds[1] === 'recipe' ? 'receitas' : 'despensa') : duplicateIds[1])
  const invalidRecord = message.match(/^An invalid (recipe|pantry) record was found in Firestore\. Export or repair it before editing this collection\.$/)
  if (invalidRecord) return translate(locale, 'invalidCollectionRecord').replace('{kind}', locale === 'pt-BR' ? (invalidRecord[1] === 'recipe' ? 'de receita' : 'da despensa') : invalidRecord[1])
  const tooManyChanges = message.match(/^This operation exceeds (\d+) Firestore changes\. Restore a smaller backup\.$/)
  if (tooManyChanges) return translate(locale, 'tooManyChanges').replace('{n}', tooManyChanges[1])
  const backupChanges = message.match(/^This backup requires more than (\d+) Firestore changes\. Divide it into smaller backups\.$/)
  if (backupChanges) return translate(locale, 'backupTooManyChanges').replace('{n}', backupChanges[1])
  const sourceHttpError = message.match(/^(Meal database|Open Food Facts) responded with HTTP (\d+)\.$/)
  if (sourceHttpError) {
    const provider = sourceHttpError[1] === 'Meal database' ? 'TheMealDB' : 'Open Food Facts'
    return locale === 'pt-BR'
      ? `O ${provider} respondeu com erro HTTP ${sourceHttpError[2]}.`
      : `${provider} responded with HTTP ${sourceHttpError[2]}.`
  }
  return message
}

export function getInitialLocale(): Locale {
  try {
    const stored = window.localStorage.getItem('recipes-vault-locale')
    return stored === 'pt-BR' ? 'pt-BR' : 'en-US'
  } catch {
    return 'en-US'
  }
}

export function saveLocale(locale: Locale): void {
  try {
    window.localStorage.setItem('recipes-vault-locale', locale)
  } catch {
    return
  }
}
